"""错开叠放的行距：瀑布图 / 对比堆叠 / CLI 瀑布图**共用这一处口径**。

规则一句话：**所有行同一个行高**（不按各行自己的峰——那等于把每行缩到各自
高度，行与行没法横向比；用户 2026-09-26 定的"不要按照各自的最高峰归一化，
所有的图"），而这个行高取 **第二高的那一行的峰 × 0.7**，**不取全场最大**。

为什么换掉"全场最大 × 0.7"（用户 2026-10-02："瀑布图……还是不行，改成行
间距小一点，让峰明显一点"）——实测这批 LMFP 的 36 个扇区：

    全场峰值 48230（χ=165° 那个扇区的 2.83° 主峰，是第二名的 3.3 倍）
    第二高 = 14753；中位扇区的峰 2586 = 全场峰值的 5.4%

旧口径下行距 = 33761，中位那一行的峰只占**一行高度的 8%**——整张图看上去
就是一把平线。改成"第二高 × 0.7"之后行距 = 10327（全场峰值的 21%），中位
行的峰占到行高的 25%、一眼看得见；只有最强的那个扇区会探进上一行（4.7 行，
那正是它该有的样子——它确实比别的强 3 倍）。

为什么忽略**一个**就够：让所有行变平的就是那个离群值本身；均匀样品（各行差
不多强）里第二高 ≈ 最大，与老口径逐位相同、不会反过来糊成一团。也正因为只
忽略一个，**行数少时同样成立**（对比图只勾两个文件时，不该让强的那一个决定
弱的那一个的可见度），比"取第 90 百分位"那种统计量在 n 很小时退化成最大值
要稳。

放在 services 而不是 GUI 模块：CLI 的 `scripts/sector_waterfall.py` 也要用
同一套口径，而它不导入任何 GUI 模块（为了一个画图常数拖进 PySide6 不划算）。
"""
import numpy as np

ROW_STEP_FACTOR = 0.7       # 行距 = 基准（第二高的行峰）× 这个系数


def row_step(per_row_peaks) -> float:
    """行距。`per_row_peaks` = 每行（扇区 / 文件 / 曲线）自己的峰值。

    非有限值与 ≤0 的值先丢掉（坏扇区整行 NaN 是预期输入，见
    plot_views._draw_waterfall），再取**第二高**的那个当基准；只有一行时
    就用它自己。一条都没有（空图）时返回 1.0——一个无量纲的占位行距，
    免得调用方再各写一个 if。
    """
    vals = np.asarray([float(p) for p in per_row_peaks], dtype=float)
    vals = np.sort(vals[np.isfinite(vals) & (vals > 0)])
    if not vals.size:
        return 1.0
    base = float(vals[-2]) if vals.size >= 2 else float(vals[-1])
    return base * ROW_STEP_FACTOR
